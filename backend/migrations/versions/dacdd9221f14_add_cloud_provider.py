def generate_id(taken: set[str]) -> str:
    while True:
        number = str(random.randint(10 ** (PK_NUM_LENGTH - 1), 10**PK_NUM_LENGTH - 1))
        grouped = "-".join(
            number[i : i + PK_GROUP_SIZE] for i in range(0, len(number), PK_GROUP_SIZE)
        )
        candidate = f"{PK_PREFIX}-{grouped}"
        if candidate not in taken:
            taken.add(candidate)
            return candidate


