def backfill_cloud_providers() -> None:
    """Insert one provider per non-deleted affiliate whose integration has a seed.

    Affiliates with integration IS NULL, or with an integration that has no seed
    (Google, SoftwareOne), get no row and keep working without validation.
    """
    bind = op.get_bind()
    accounts = bind.execute(
        sa.text(
            "SELECT id, integration FROM accounts "
            "WHERE type = 'affiliate' AND integration IS NOT NULL AND status <> 'deleted' "
            "ORDER BY id"
        )
    ).all()

    taken: set[str] = set()
    rows = []
    for account_id, integration in accounts:
        seed = CLOUD_PROVIDER_SEEDS.get(integration)
        if seed is None:
            continue
        rows.append({"id": generate_id(taken), "account_id": account_id, **seed})
    if rows:
        op.bulk_insert(cloud_providers, rows)


